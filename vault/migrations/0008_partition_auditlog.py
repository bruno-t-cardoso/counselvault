"""Turn the audit log into a table partitioned by month.

The audit log only grows, and is mostly read by recent date. Partitioning by
month keeps each index small, lets the planner skip months a query cannot
match, and makes it possible to archive or detach an old month without a
long-running DELETE.

PostgreSQL cannot convert a table in place, so this builds the partitioned
table, copies the rows across and drops the old one. Columns are unchanged, so
Django's model state needs no update. Not reversible.

Access rules carry over and are tightened:
- The application role reads and inserts through the parent table only. It has
  no privileges on the partitions themselves, because a partition queried
  directly would not get the parent's row-level security policy.
- Partitions also carry the policy and a TRUNCATE trigger, as a second layer.
"""

from django.conf import settings
from django.db import migrations

TENANT_CHECK = "firm_id = NULLIF(current_setting('app.current_firm_id', true), '')::bigint"
COLUMNS = "id, firm_id, actor_id, action, document_id, matter_id, metadata, created_at"


def partition(apps, schema_editor):
    app_role = schema_editor.quote_name(settings.DB_APP_USER)
    statements = [
        # 1. Move the old table out of the way. NO FORCE lets the owner read every
        #    firm's rows for the copy.
        "ALTER TABLE vault_auditlog NO FORCE ROW LEVEL SECURITY",
        "ALTER TABLE vault_auditlog RENAME TO vault_auditlog_unpartitioned",
        "ALTER INDEX vault_auditlog_pkey RENAME TO vault_auditlog_unpartitioned_pkey",
        "ALTER INDEX audit_firm_doc_created RENAME TO audit_firm_doc_created_old",
        "ALTER INDEX audit_firm_matter_created RENAME TO audit_firm_matter_created_old",
        # 2. The partitioned table. The partition key must be part of the primary key.
        """
        CREATE TABLE vault_auditlog (
            id bigint GENERATED BY DEFAULT AS IDENTITY,
            firm_id bigint NOT NULL REFERENCES vault_firm (id) DEFERRABLE INITIALLY DEFERRED,
            actor_id bigint NOT NULL
                REFERENCES vault_attorney (id) DEFERRABLE INITIALLY DEFERRED,
            action varchar(40) NOT NULL,
            document_id uuid REFERENCES vault_document (id) DEFERRABLE INITIALLY DEFERRED,
            matter_id uuid REFERENCES vault_matter (id) DEFERRABLE INITIALLY DEFERRED,
            metadata jsonb NOT NULL,
            created_at timestamptz NOT NULL,
            PRIMARY KEY (id, created_at),
            CONSTRAINT audit_has_a_subject
                CHECK (document_id IS NOT NULL OR matter_id IS NOT NULL)
        ) PARTITION BY RANGE (created_at)
        """,
        "CREATE INDEX audit_firm_doc_created"
        " ON vault_auditlog (firm_id, document_id, created_at DESC)",
        "CREATE INDEX audit_firm_matter_created"
        " ON vault_auditlog (firm_id, matter_id, created_at DESC)",
        "CREATE INDEX audit_actor ON vault_auditlog (actor_id)",
        # 3. Helpers for creating partitions, used here and by `ensure_audit_partitions`.
        f"""
        CREATE FUNCTION vault_lock_down_auditlog_partition(part regclass) RETURNS void
        LANGUAGE plpgsql AS $$
        BEGIN
            EXECUTE format('ALTER TABLE %s ENABLE ROW LEVEL SECURITY', part);
            EXECUTE format('ALTER TABLE %s FORCE ROW LEVEL SECURITY', part);
            EXECUTE format(
                'CREATE POLICY tenant_isolation ON %s USING ({TENANT_CHECK.replace("'", "''")})'
                ' WITH CHECK ({TENANT_CHECK.replace("'", "''")})', part);
            EXECUTE format('REVOKE ALL ON %s FROM {app_role}', part);
            EXECUTE format(
                'CREATE TRIGGER auditlog_no_truncate BEFORE TRUNCATE ON %s'
                ' FOR EACH STATEMENT EXECUTE FUNCTION vault_auditlog_append_only()', part);
        END
        $$
        """,
        """
        CREATE FUNCTION vault_ensure_auditlog_partition(month date) RETURNS text
        LANGUAGE plpgsql AS $$
        DECLARE
            first_day date := date_trunc('month', month)::date;
            part text := 'vault_auditlog_' || to_char(first_day, 'YYYY_MM');
        BEGIN
            IF to_regclass(part) IS NULL THEN
                EXECUTE format(
                    'CREATE TABLE %I PARTITION OF vault_auditlog FOR VALUES FROM (%L) TO (%L)',
                    part,
                    first_day::timestamp AT TIME ZONE 'UTC',
                    (first_day + interval '1 month')::timestamp AT TIME ZONE 'UTC');
                PERFORM vault_lock_down_auditlog_partition(part::regclass);
            END IF;
            RETURN part;
        END
        $$
        """,
        # 4. Partitions: a catch-all so an insert can never fail for lack of a partition,
        #    every month that already has rows, and this month plus the next three.
        "CREATE TABLE vault_auditlog_default PARTITION OF vault_auditlog DEFAULT",
        "SELECT vault_lock_down_auditlog_partition('vault_auditlog_default')",
        """
        SELECT vault_ensure_auditlog_partition(month::date)
        FROM (
            SELECT DISTINCT date_trunc('month', created_at AT TIME ZONE 'UTC') AS month
            FROM vault_auditlog_unpartitioned
        ) AS months
        """,
        """
        SELECT vault_ensure_auditlog_partition(
            (date_trunc('month', now() AT TIME ZONE 'UTC') + make_interval(months => n))::date)
        FROM generate_series(0, 3) AS n
        """,
        # 5. Copy the rows and continue the id sequence after them.
        f"INSERT INTO vault_auditlog ({COLUMNS}) SELECT {COLUMNS} FROM vault_auditlog_unpartitioned",
        """
        SELECT setval(pg_get_serial_sequence('vault_auditlog', 'id'),
                      COALESCE(max(id), 0) + 1, false)
        FROM vault_auditlog
        """,
        "DROP TABLE vault_auditlog_unpartitioned",
        # 6. Same protections as before on the parent. Row triggers on a partitioned
        #    table apply to every partition, including ones created later.
        "ALTER TABLE vault_auditlog ENABLE ROW LEVEL SECURITY",
        "ALTER TABLE vault_auditlog FORCE ROW LEVEL SECURITY",
        f"CREATE POLICY tenant_isolation ON vault_auditlog"
        f" USING ({TENANT_CHECK}) WITH CHECK ({TENANT_CHECK})",
        "CREATE TRIGGER auditlog_no_update_or_delete BEFORE UPDATE OR DELETE ON vault_auditlog"
        " FOR EACH ROW EXECUTE FUNCTION vault_auditlog_append_only()",
        "CREATE TRIGGER auditlog_no_truncate BEFORE TRUNCATE ON vault_auditlog"
        " FOR EACH STATEMENT EXECUTE FUNCTION vault_auditlog_append_only()",
        f"REVOKE UPDATE, DELETE ON vault_auditlog FROM {app_role}",
    ]
    for statement in statements:
        # params=None: the SQL contains format() placeholders such as %s that are not ours.
        schema_editor.execute(statement, params=None)


